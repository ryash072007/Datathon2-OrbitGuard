"""Render the review from retrieved LinuxONE artifacts, without hand-entered results."""

import argparse
import json
from pathlib import Path
import re


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--artifacts', type=Path, default=Path('artifacts/review-linuxone'))
    parser.add_argument('--before', type=Path, default=Path('artifacts/linuxone/ml/accuracy_audit.json'))
    parser.add_argument('--output', type=Path, default=Path('docs/ACCURACY_REVIEW.md'))
    options = parser.parse_args()
    root = options.artifacts
    accuracy = json.loads((root / 'ml/accuracy_audit.json').read_text())
    forecast_evidence = json.loads((root / 'ml/evidence.json').read_text())
    residual_ranking = forecast_evidence['ranking_comparison']
    residual_interval = residual_ranking['paired_bootstrap_ap_difference_ci95']
    triage = json.loads((root / 'ml/triage_evidence.json').read_text())
    physics = json.loads((root / 'physics/benchmark.json').read_text())
    validation = json.loads((root / 'physics/validation.json').read_text())
    runtime = json.loads((root / 'runtime/metrics.json').read_text())
    test_log = (root / 'regression-tests.out').read_text()
    passed_tests = re.search(r'(\d+) passed', test_log)
    if not passed_tests or runtime['status'] != 'completed':
        raise ValueError('Complete passing regression and runtime evidence is required')
    before = json.loads(options.before.read_text()) if options.before.exists() else None
    rows = []
    for name, result in accuracy['methods'].items():
        rows.append(f"| {name} | {result['challenge_loss']:.6f} | {result['recall']:.1%} | {result['precision']:.1%} | {result['fn']} | {result['fp']} | {result['log10_mae']:.3f} |")
    baseline = accuracy['methods']['latest_baseline']
    recall_interval = baseline['recall_ci95']
    shrinkage_interval = accuracy['shrinkage_loss_difference']['ci95']
    triage_interval = triage['paired_bootstrap']['ci95']
    fixed = accuracy['methods']['learned_residual']
    correction = ''
    if before:
        previous = before['methods']['learned_residual']['log10_mae']
        correction = f"The raw-risk floor fix reduces the learned forecast's mean absolute log10 error from **{previous:.3f} to {fixed['log10_mae']:.3f}** on the same frozen model and events. This repairs the numerical forecast, but its ESA challenge loss remains worse than the default baseline. It is not evidence of better collision prediction.\n"
    policies = physics['policies']
    maximum_error = max(case['relative_error'] for case in validation['cases'])
    contents = f"""# Accuracy review on IBM LinuxONE

Generated by `scripts/render_accuracy_review.py` from `artifacts/review-linuxone`.
Audit timestamp: {accuracy['generated_at']}; architecture: **{accuracy['architecture']}**.

## What changed

- Preserve raw low-probability information when applying learned residuals; zero correction now preserves the input instead of flooring it to 10^-12.
- Split closest-approach searches at burn discontinuities.
- Resolve narrow Gaussian integrands instead of silently integrating an almost-certain collision as zero.
- Publish tightly verified risks, distinguish rejected verification, and remove withheld recommendation paths.
- Refuse stale model evaluation metrics and stop the evidence pipeline on its first failure.

## Real-data forecasting

The target is the later **reported ESA risk estimate**, not a collision outcome.
There are {accuracy['test_events']:,} test events, of which {accuracy['high_risk_events']} have final risk at least 10^-6.

| Method | ESA loss, lower better | Recall | Precision | Missed | False alarms | Raw log10 MAE |
|---|---:|---:|---:|---:|---:|---:|
{chr(10).join(rows)}

{correction}
Baseline recall has a 95% Wilson interval of **{recall_interval[0]:.1%} to {recall_interval[1]:.1%}**.
Always predicting low risk would score {baseline['always_low_risk_accuracy']:.1%} overall accuracy, despite detecting none of the high-risk encounters. Do not present a headline accuracy percentage without recall and missed alerts.

## Experimental methods were not promoted

The corrected residual model retains useful **triage ranking**: average precision is **{residual_ranking['learned_average_precision']:.4f}**, compared with **{residual_ranking['latest_average_precision']:.4f}** for latest risk. Its paired AP-difference interval is **[{residual_interval[0]:+.4f}, {residual_interval[1]:+.4f}]**. This measures review ordering, not the accuracy of its numerical risk forecast or recall at a fixed threshold.

The shrinkage coefficient was fit only on training events and frozen before this evaluation loaded the released labels. Its loss difference against baseline has a paired 95% interval of **[{shrinkage_interval[0]:+.4f}, {shrinkage_interval[1]:+.4f}]**. An interval crossing zero does not establish a reliable gain. The default remains the latest-risk baseline.

The separate classifier selects its configuration and alert threshold using training-event out-of-fold predictions only. Its score estimates whether the later risk estimate is high; it is **not collision probability Pc** and is not calibrated.

| Ranking | Average precision | Top-10% recall | Recall at frozen threshold | Missed | False alarms |
|---|---:|---:|---:|---:|---:|
| Latest risk | {triage['baseline']['average_precision']:.4f} | {triage['baseline']['top_10_percent_recall']:.1%} | {triage['baseline']['recall']:.1%} | {triage['baseline']['fn']} | {triage['baseline']['fp']} |
| Experimental classifier | {triage['metrics']['average_precision']:.4f} | {triage['metrics']['top_10_percent_recall']:.1%} | {triage['metrics']['recall']:.1%} | {triage['metrics']['fn']} | {triage['metrics']['fp']} |

Classifier-minus-baseline AP difference, paired 95% interval: **[{triage_interval[0]:+.4f}, {triage_interval[1]:+.4f}]**.
Compare false alarms and missed alerts together. This classifier does not establish superior ranking when the interval crosses zero; it also does not replace the existing residual ranking.

## Independent numerical checks and synthetic planning

All {len(validation['cases'])} pinned NASA reference cases pass; largest relative error **{maximum_error:.3g}**. All {len(validation['numerical_checks'])} additional numerical checks pass.

The corrected planner completes {physics['scenario_count']} frozen synthetic scenarios, with {physics['failed_scenarios']} failed computations:

| Policy | Acceptable plans | New secondary hazards | Unsafe selections | Correct abstentions |
|---|---:|---:|---:|---:|
| No action | {policies['no_action']['acceptable_plan_count']} | {policies['no_action']['secondary_hazards_introduced']} | {policies['no_action']['unsafe_selected_count']} | {policies['no_action']['correct_abstentions']} |
| Avoid primary only | {policies['pair_only']['acceptable_plan_count']} | {policies['pair_only']['secondary_hazards_introduced']} | {policies['pair_only']['unsafe_selected_count']} | {policies['pair_only']['correct_abstentions']} |
| OrbitGuard | {policies['orbitguard']['acceptable_plan_count']} | {policies['orbitguard']['secondary_hazards_introduced']} | {policies['orbitguard']['unsafe_selected_count']} | {policies['orbitguard']['correct_abstentions']} |

These scenarios deliberately stress secondary hazards and are not real traffic prevalence. NASA cases verify selected probability integrals, not complete operational orbit predictions. The finite candidate set, two-body gravity, prescribed covariance and three uncertainty scales remain prototype limitations; partial horizon encounters and slow co-orbital cases remain outside scope.

## Provenance and reproducibility

The final LinuxONE regression run passes **{passed_tests.group(1)} tests**. Runtime measurements below exclude network/browser overhead and had no recorded forecast, screening, serial or parallel failures:

| Workload | Runs | Median | p95 |
|---|---:|---:|---:|
| Forecast service call | {runtime['forecast']['count']} | {runtime['forecast']['p50_ms']:.2f} ms | {runtime['forecast']['p95_ms']:.2f} ms |
| Full screening with verification | {runtime['screening']['count']} | {runtime['screening']['p50_ms'] / 1000:.2f} s | {runtime['screening']['p95_ms'] / 1000:.2f} s |

{runtime['parallel_comparison']['workers']} workers completed the same {runtime['parallel_comparison']['workloads']} screening workloads with **{runtime['parallel_comparison']['speedup']:.2f}x** measured speedup, including process-pool startup.

- Frozen forecast model before evaluation: `{accuracy['fingerprints']['model_before']}`.
- Frozen forecast model after evaluation: `{accuracy['fingerprints']['model_after']}`.
- Prediction source: `{accuracy['fingerprints']['prediction_source_sha256']}`.
- Frozen classifier: `{triage['validation']['frozen_model_sha256_before_labels']}`.
- Scenario suite: `{physics['suite_sha256']}`.
- The public test set was already evaluated by earlier project versions. This review is a **retrospective recheck**, not a new blind test. No test labels were used to select these new coefficients, classifier configuration or alert threshold.

Reproduce on the native LinuxONE environment after preparing the official data and frozen forecast model:

```bash
python -m pytest -q
orbitguard evaluate
orbitguard audit-accuracy
orbitguard train-triage
orbitguard evaluate-triage
orbitguard validate-physics
orbitguard benchmark-planner --count 50 --runtime-repetitions 5
orbitguard benchmark-runtime
```

Source definitions: [ESA scoring](https://kelvins.esa.int/collision-avoidance-challenge/scoring/), [ESA dataset](https://zenodo.org/records/4463683), [NASA reference tools](https://github.com/nasa/CARA_Analysis_Tools). ESA data: CC BY 4.0, European Space Agency.
"""
    options.output.parent.mkdir(parents=True, exist_ok=True)
    options.output.write_text(contents)
    evidence = options.output.parent / 'evidence'
    evidence.mkdir(exist_ok=True)
    for name, value in (('accuracy-review.json', accuracy), ('triage-review.json', triage)):
        (evidence / name).write_text(json.dumps(value, indent=2, allow_nan=False) + '\n')
    if before:
        (evidence / 'accuracy-before-fix.json').write_text(json.dumps(before, indent=2, allow_nan=False) + '\n')
    (evidence / 'linuxone-runtime-review.json').write_text(json.dumps(runtime, indent=2, allow_nan=False) + '\n')
    (evidence / 'linuxone-physics-review.json').write_text(json.dumps({
        'validation': validation, 'benchmark': {key: value for key, value in physics.items() if key != 'scenarios'},
        'regression_output': test_log,
    }, indent=2, allow_nan=False) + '\n')
    print(options.output)


if __name__ == '__main__':
    main()
