"""Render docs/RESULTS.md from generated evidence artifacts (never hand-typed numbers).

Usage: python3 scripts/render_results.py [artifact_dir]
Default artifact_dir is artifacts/linuxone (fetched with scripts/linuxone.py fetch-results).
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def load(base: Path, name: str) -> dict:
    return json.loads((base / name).read_text())


def f(value, digits=4) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.{digits}e}" if value and abs(value) < 1e-3 else f"{value:.{digits}f}"
    return str(value)


def main(argv: list[str]) -> int:
    base = Path(argv[0]) if argv else ROOT / "artifacts" / "linuxone"
    ml = load(base, "ml/evidence.json")
    meta = load(base, "ml/model_metadata.json")
    val = load(base, "physics/validation.json")
    bench = load(base, "physics/benchmark.json")
    runtime = load(base, "runtime/metrics.json")
    env = runtime["environment"]
    status_log = (base / "pipeline/status.log").read_text().strip() if (base / "pipeline/status.log").is_file() else ""

    names = {
        "clipped_latest_baseline": "Latest-risk baseline (ESA clipped)",
        "learned_residual_scored": "Learned residual GBM (ESA clipped)",
        "constant_minus_5": "Constant −5",
        "latest_known_raw": "Latest-risk, raw (ranking only)",
        "learned_residual_raw": "Learned residual GBM, raw (ranking only)",
    }
    rows = {m["name"]: m for m in ml["metrics"]}
    v = ml["validation"]
    rank = ml["ranking_comparison"]

    out = [
        "# OrbitGuard — measured results",
        "",
        f"Generated by `scripts/render_results.py` from `{base.relative_to(ROOT) if base.is_relative_to(ROOT) else base}`. "
        "Do not edit numbers by hand; regenerate instead.",
        "",
        f"**Platform:** {env['architecture']} · {env['platform']} {env['os_release']} · Python {env['python_version']} · "
        f"{env['available_cpus']} CPUs · LinuxONE: **{'yes' if env['is_linuxone'] else 'no'}**",
        "",
        "Packages: " + ", ".join(f"{k} {v_}" for k, v_ in env["packages"].items() if v_),
        "",
        "## 1. Historical forecasting — ESA Collision Avoidance Challenge (held-out test set)",
        "",
        f"- Training events (eligible): {meta['data']['train_events']} ({meta['data']['train_high_risk_events']} high-risk); "
        f"test events: {meta['data']['test_events']} ({rows['clipped_latest_baseline']['high_risk_event_count']} high-risk).",
        f"- Inputs use only messages ≥ {meta['cutoff_days']:g} days before closest approach; target is the final reported "
        "log10 risk (< 1 day). Labels read only after model freeze.",
        f"- Frozen model SHA256 before labels: `{v['frozen_model_sha256_before_labels']}`; after evaluation: "
        f"`{v['model_sha256_after_evaluation']}`.",
        f"- Published ESA baseline loss ≈ {v['published_clipped_latest_loss_rounded']}; reproduced: "
        f"**{v['reproduced_clipped_latest_loss']:.6f}** (reproduced: {v['published_baseline_reproduced']}).",
        "",
        "| Method | ESA loss ↓ | F2 ↑ | Recall | Precision | TP | FP | FN |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for key in ["clipped_latest_baseline", "learned_residual_scored", "constant_minus_5"]:
        r = rows[key]
        out.append(f"| {names[key]} | {f(r['challenge_loss'])} | {f(r['f2'])} | {f(r['recall'])} | {f(r['precision'])} | "
                   f"{r['tp']} | {r['fp']} | {r['fn']} |")
    boot = v["paired_bootstrap"]
    out += [
        "",
        f"Paired bootstrap ({boot['valid_repeats']} resamples), learned minus baseline loss, 95% CI: "
        f"[{boot['ci95'][0]:.3f}, {boot['ci95'][1]:.3f}] — **the baseline is the better point forecast**, and "
        f"cross-validation already selected it (`selected_method = {meta['selected_method']}`).",
        "",
        "### Analyst triage ranking (unclipped scores)",
        "",
        "| Ranking | Average precision | Top-10% recall |",
        "|---|---:|---:|",
        f"| {names['latest_known_raw']} | {f(rank['latest_average_precision'])} | {f(rows['latest_known_raw']['top_10_percent_recall'])} |",
        f"| {names['learned_residual_raw']} | {f(rank['learned_average_precision'])} | {f(rows['learned_residual_raw']['top_10_percent_recall'])} |",
        "",
        f"AP difference 95% paired-bootstrap CI: [{rank['paired_bootstrap_ap_difference_ci95'][0]:.4f}, "
        f"{rank['paired_bootstrap_ap_difference_ci95'][1]:.4f}] (positive favours the learned ranking).",
        "",
        "## 2. Collision-probability implementation — NASA CARA reference cases",
        "",
        f"Reference commit `{val['reference_commit']}`. {val['attribution']}",
        "",
        "| Case | Expected Pc | OrbitGuard Pc | Relative error | Result |",
        "|---|---:|---:|---:|---|",
    ]
    for c in val["cases"]:
        out.append(f"| {c['name']} | {c['expected']:.6e} | {c['actual']:.6e} | {c['relative_error']:.2e} | "
                   f"{'Pass' if c['passed'] else 'Fail'} |")
    out += ["", "Additional checks: " + "; ".join(
        f"{c['name']} {'(pass)' if c['passed'] else '(FAIL)'}" for c in val["numerical_checks"]) + ".", ""]

    out += [
        "## 3. Manoeuvre screening — frozen 50-scenario synthetic suite",
        "",
        f"Suite SHA256 `{bench['suite_sha256']}` · composition {bench['suite_distribution']} · per-encounter "
        f"threshold Pc ≤ {bench['risk_threshold']:g} at every uncertainty scale {bench['uncertainty_scales']} · "
        f"{len(bench['candidate_grid']['burn_times_seconds']) * len(bench['candidate_grid']['delta_v_mps']) + 1} candidates per scenario.",
        "The composition is a stress-test design, not real-world encounter prevalence.",
        "",
        "| Policy | Acceptable plans | Secondary hazards introduced | Unsafe selections | Correct abstentions | Mean Δv (m/s) | Max worst Pc |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    labels = {"no_action": "No action", "pair_only": "Original-pair avoidance", "orbitguard": "**OrbitGuard (all objects)**"}
    n = bench["scenario_count"]
    for key in ["no_action", "pair_only", "orbitguard"]:
        p = bench["policies"][key]
        out.append(f"| {labels[key]} | {p['acceptable_plan_count']}/{n} | {p['secondary_hazards_introduced']} | "
                   f"{p['unsafe_selected_count']} | {p['correct_abstentions']} | {p['mean_delta_v_mps']:.4f} | "
                   f"{f(p['max_worst_pc'], 2)} |")
    out += [f"", f"Failed scenarios: {bench['failed_scenarios']}.", ""]

    fc, sc, par = runtime["forecast"], runtime["screening"], runtime["parallel_comparison"]
    out += [
        "## 4. Runtime on this platform",
        "",
        "| Workload | Runs | p50 | p95 |",
        "|---|---:|---:|---:|",
        f"| Forecast (service call) | {fc['count']} | {fc['p50_ms']:.2f} ms | {fc['p95_ms']:.2f} ms |",
        f"| Full 37-candidate screening incl. verification | {sc['count']} | {sc['p50_ms']:.0f} ms | {sc['p95_ms']:.0f} ms |",
        "",
        f"Scenario-level parallelism: {par['workloads']} screenings, serial {par['serial_seconds']:.2f} s vs "
        f"{par['workers']} workers {par['parallel_seconds']:.2f} s → **{par['speedup']:.2f}× speedup** "
        f"(includes process-pool start-up).",
        "",
        f"Model training time on this platform: {meta['fit_elapsed_seconds']:.1f} s (16 configurations × 3 folds + final fit).",
        "",
    ]
    if status_log:
        out += ["## 5. Pipeline log", "", "```text", status_log, "```", ""]
    out += ["## Limitations", ""] + [f"- {item}" for item in ml["limitations"]] + [
        "- Simulator: two-body gravity, impulsive tangential burns, prescribed (not propagated) RTN uncertainty; "
        "decision support only, not flight software.", ""]

    text = "\n".join(out)
    target = ROOT / "docs" / "RESULTS.md"
    target.write_text(text)
    print(f"Wrote {target} ({hashlib.sha256(text.encode()).hexdigest()[:12]})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
